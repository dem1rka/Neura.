import { expect, test } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { allQuestions } from "../../src/features/screening/content";
import { demoCohort } from "../../src/features/screening/engine";
import { exportCSV, exportJSON } from "../../src/features/screening/io";

test("completes both questionnaires, saves, exports and rejects invalid/duplicate imports", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await page.goto("/questionnaire");
  await page.getByRole("button", { name: "Новое наблюдение", exact: true }).click();
  await page.getByLabel("Код ребёнка (без ФИО)").fill("CASE-001");
  await page.getByLabel("Возраст в месяцах", { exact: true }).fill("84");
  for (const q of allQuestions.slice(0, 8)) await page.locator(`input[name="${q.id}"][value="2"]`).check();
  await page.getByRole("button", { name: "Самочувствие и повседневная жизнь", exact: true }).click();
  for (const q of allQuestions.slice(8)) await page.locator(`input[name="${q.id}"][value="1"]`).check();
  await page.getByLabel("Есть ли утрата ранее освоенных навыков?").selectOption("true");
  await page.getByText("Добавить результат официального бланка", { exact: true }).click();
  await page.getByRole("combobox", { name: "Методика", exact: true }).selectOption("aq10");
  await page.getByLabel("Балл AQ-10 (0–10)").fill("6");
  await page.getByLabel("Отсутствие интеллектуальных нарушений подтверждено?").selectOption("true");
  await page.getByRole("button", { name: "Сохранить и разобрать" }).click();
  await expect(page.getByText("Порог направления достигнут", { exact: true })).toBeVisible();
  await expect(page.getByText("Отмечена утрата навыков", { exact: true })).toBeVisible();
  await expect(page.getByText("Все ответы известны.", { exact: false })).toHaveCount(2);
  const exportEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "JSON", exact: true }).click();
  const download = await exportEvent;
  const exported = JSON.parse(await readFile((await download.path())!, "utf8"));
  expect(exported.records[0].answers.soc1).toBe(2);
  expect(exported.records[0].answers.sleep1).toBe(1);
  expect(exported.records[0].demo).toBe(false);
  await page.reload();
  await page.getByRole("tab", { name: "Анализ и экспертная система" }).click();
  await expect(page.getByRole("heading", { name: "CASE-001", exact: true })).toBeVisible();
  await page.getByRole("tab", { name: "Заполнить анкеты", exact: true }).click();
  await page.getByLabel("Файл с ответами", { exact: true }).setInputFiles({ name: "duplicate.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(exported)) });
  await expect(page.getByRole("alert")).toContainText("Код ребёнка повторяется");
  const invalid = structuredClone(exported);
  invalid.records[0].id = "BAD"; invalid.records[0].answers.soc1 = 99;
  await page.getByLabel("Файл с ответами", { exact: true }).setInputFiles({ name: "bad.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(invalid)) });
  await expect(page.getByRole("alert")).toContainText("Ответ должен быть");
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("neura.v1.screening")!).length)).toBe(1);
  await page.getByLabel("Файл с ответами", { exact: true }).setInputFiles({ name: "demo.csv", mimeType: "text/csv", buffer: Buffer.from(exportCSV(demoCohort.map((c) => c.record))) });
  await expect(page.getByRole("status")).toContainText("Загружено записей: 8");
  await expect(page.getByRole("heading", { name: "DEMO-001", exact: true })).toBeVisible();
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("neura.v1.screening")!).length)).toBe(9);
  await page.getByRole("combobox", { name: "Наблюдение", exact: true }).selectOption("local:CASE-001");
  await page.screenshot({ path: "test-results/screening-desktop.png", fullPage: true });
  expect(errors).toEqual([]);
});

